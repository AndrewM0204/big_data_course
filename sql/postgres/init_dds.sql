-- sql/postgres/init_dds.sql
-- DDL DDS-слоя ЛР2: схема «снежинка», измерения, факты, staging и результаты DQ.
-- Файл идемпотентен и не зависит от ODS-таблиц (по алфавиту исполняется раньше init_ods.sql).

CREATE SCHEMA IF NOT EXISTS dds;

-- ==========================================
-- ИЗМЕРЕНИЯ
-- ==========================================
-- Календарь: date_id — YYYYMMDD (UTC), заполняется зоной А и страховочным таском dds_facts_dag.
CREATE TABLE IF NOT EXISTS dds.dim_date (
    date_id    INTEGER PRIMARY KEY,
    date       DATE NOT NULL UNIQUE,
    year       SMALLINT NOT NULL,
    month      SMALLINT NOT NULL,
    day        SMALLINT NOT NULL,
    quarter    SMALLINT NOT NULL,
    is_weekend BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dds.dim_genre (
    genre_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dds.dim_developer (
    developer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    developer_name TEXT NOT NULL UNIQUE
);

-- SCD Type 2: у игры может быть несколько версий, актуальная помечена is_current.
CREATE TABLE IF NOT EXISTS dds.dim_game (
    game_sk         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appid           BIGINT NOT NULL,
    name            TEXT,
    is_free         BOOLEAN,
    release_date    TEXT,
    developer_id    INTEGER REFERENCES dds.dim_developer (developer_id),
    genre_id        INTEGER REFERENCES dds.dim_genre (genre_id),
    effective_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expiration_date DATE NOT NULL DEFAULT DATE '9999-12-31',
    is_current      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_dim_game_period CHECK (expiration_date >= effective_date::date)
);

-- Защита от двух «текущих» версий одной игры.
CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_game_current_appid
    ON dds.dim_game (appid) WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_game_appid ON dds.dim_game (appid);

CREATE TABLE IF NOT EXISTS dds.dim_author (
    steamid          TEXT PRIMARY KEY,
    num_reviews      INTEGER NOT NULL DEFAULT 0,
    playtime_forever INTEGER NOT NULL DEFAULT 0,
    first_seen_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ==========================================
-- ФАКТЫ
-- ==========================================
-- Отзыв на уровне отдельной рецензии; отрицательные значения не блокируем —
-- их ловит DQ-проверка аномалий.
CREATE TABLE IF NOT EXISTS dds.fact_review (
    review_id         TEXT PRIMARY KEY,
    game_sk           INTEGER NOT NULL REFERENCES dds.dim_game (game_sk),
    author_steamid    TEXT REFERENCES dds.dim_author (steamid),
    date_id           INTEGER NOT NULL REFERENCES dds.dim_date (date_id),
    language          TEXT,
    voted_up          BOOLEAN,
    votes_up          INTEGER,
    votes_funny       INTEGER,
    weighted_score    NUMERIC(6, 5),
    timestamp_created TIMESTAMPTZ NOT NULL,
    loaded_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fact_review_game_date
    ON dds.fact_review (game_sk, date_id);

CREATE INDEX IF NOT EXISTS idx_fact_review_date
    ON dds.fact_review (date_id);

-- Часовая агрегация онлайна; ключ — игра, день, час.
CREATE TABLE IF NOT EXISTS dds.fact_player_activity (
    game_sk     INTEGER NOT NULL REFERENCES dds.dim_game (game_sk),
    date_id     INTEGER NOT NULL REFERENCES dds.dim_date (date_id),
    hour        SMALLINT NOT NULL CHECK (hour BETWEEN 0 AND 23),
    avg_players NUMERIC(12, 2) NOT NULL CHECK (avg_players >= 0),
    max_players BIGINT NOT NULL CHECK (max_players >= 0),
    samples     INTEGER NOT NULL CHECK (samples > 0),
    loaded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (game_sk, date_id, hour),
    CONSTRAINT chk_fact_player_activity_max CHECK (max_players >= avg_players)
);

CREATE INDEX IF NOT EXISTS idx_fact_player_activity_date
    ON dds.fact_player_activity (date_id);

CREATE INDEX IF NOT EXISTS idx_fact_player_activity_hour
    ON dds.fact_player_activity (date_id, hour);

-- ==========================================
-- STAGING (UNLOGGED)
-- ==========================================
-- Промежуточные буферы загрузки: очищаются в транзакции каждого запуска.
CREATE UNLOGGED TABLE IF NOT EXISTS dds.stg_review (
    review_id               TEXT,
    appid                   BIGINT,
    date_id                 INTEGER,
    language                TEXT,
    voted_up                BOOLEAN,
    votes_up                INTEGER,
    votes_funny             INTEGER,
    weighted_score          NUMERIC(6, 5),
    timestamp_created       TIMESTAMPTZ,
    author_steamid          TEXT,
    author_num_reviews      INTEGER,
    author_playtime_forever INTEGER
);

CREATE UNLOGGED TABLE IF NOT EXISTS dds.stg_player_activity (
    appid       BIGINT,
    date_id     INTEGER,
    hour        SMALLINT,
    avg_players NUMERIC(12, 2),
    max_players BIGINT,
    samples     INTEGER
);

-- ==========================================
-- DATA QUALITY
-- ==========================================
-- История DQ-проверок: одна строка на проверку и запуск.
CREATE TABLE IF NOT EXISTS dds.dq_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_name   TEXT NOT NULL,
    run_id       TEXT,
    check_type   TEXT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('passed', 'warning', 'error')),
    severity     TEXT,
    metric_value NUMERIC,
    threshold    NUMERIC,
    details      JSONB,
    checked_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_dq_results_check_checked_at
    ON dds.dq_results (check_name, checked_at DESC);

CREATE INDEX IF NOT EXISTS idx_dq_results_run_id
    ON dds.dq_results (run_id);

-- ==========================================
-- КОНТРАКТ ODS: steam.ods_reviews (зона А)
-- ==========================================
-- Целевая структура миграции отзывов из Mongo в Postgres:
-- плоские author_*-колонки вместо вложенного JSON. Секция создаёт свою таблицу
-- и на остальные ODS-таблицы не ссылается.
CREATE SCHEMA IF NOT EXISTS steam;

CREATE TABLE IF NOT EXISTS steam.ods_reviews (
    review_id                   TEXT PRIMARY KEY,
    appid                       BIGINT,
    language                    TEXT,
    review_text                 TEXT,
    voted_up                    BOOLEAN,
    votes_up                    INTEGER,
    votes_funny                 INTEGER,
    weighted_vote_score         NUMERIC(6, 5),
    comment_count               INTEGER,
    steam_purchase              BOOLEAN,
    received_for_free           BOOLEAN,
    written_during_early_access BOOLEAN,
    refunded                    BOOLEAN,
    timestamp_created           TIMESTAMPTZ,
    timestamp_updated           TIMESTAMPTZ,
    author_steamid              TEXT,
    author_num_reviews          INTEGER,
    author_playtime_forever     INTEGER,
    author_playtime_at_review   INTEGER,
    collected_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ods_reviews_appid
    ON steam.ods_reviews (appid);

CREATE INDEX IF NOT EXISTS idx_ods_reviews_timestamp_created
    ON steam.ods_reviews (timestamp_created DESC);

CREATE INDEX IF NOT EXISTS idx_ods_reviews_author_steamid
    ON steam.ods_reviews (author_steamid);
