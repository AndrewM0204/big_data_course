CREATE SCHEMA IF NOT EXISTS marts;

CREATE TABLE IF NOT EXISTS marts.mart_game_daily_metrics (
    activity_date       DATE NOT NULL,
    game_sk             BIGINT NOT NULL,
    appid               BIGINT NOT NULL,
    game_name           TEXT,
    is_free             BOOLEAN,
    review_count        BIGINT NOT NULL DEFAULT 0,
    positive_reviews    BIGINT NOT NULL DEFAULT 0,
    positive_ratio      NUMERIC(6, 4),
    avg_weighted_score  NUMERIC(8, 5),
    avg_players         NUMERIC(12, 2),
    max_players         BIGINT,
    samples             BIGINT NOT NULL DEFAULT 0,
    loaded_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (activity_date, game_sk)
);

CREATE INDEX IF NOT EXISTS idx_mart_game_daily_metrics_appid
    ON marts.mart_game_daily_metrics (appid);

CREATE INDEX IF NOT EXISTS idx_mart_game_daily_metrics_date
    ON marts.mart_game_daily_metrics (activity_date);

CREATE INDEX IF NOT EXISTS idx_mart_game_daily_metrics_game_date
    ON marts.mart_game_daily_metrics (game_sk, activity_date);

CREATE TABLE IF NOT EXISTS marts.mart_genre_daily_metrics (
    activity_date       DATE NOT NULL,
    genre_id            INT NOT NULL,
    genre_name          TEXT,
    review_count        BIGINT NOT NULL DEFAULT 0,
    positive_reviews    BIGINT NOT NULL DEFAULT 0,
    positive_ratio      NUMERIC(6, 4),
    avg_weighted_score  NUMERIC(8, 5),
    games_count         BIGINT NOT NULL DEFAULT 0,
    avg_players         NUMERIC(12, 2),
    max_players         BIGINT,
    samples             BIGINT NOT NULL DEFAULT 0,
    loaded_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (activity_date, genre_id)
);

CREATE INDEX IF NOT EXISTS idx_mart_genre_daily_metrics_genre
    ON marts.mart_genre_daily_metrics (genre_id);

CREATE INDEX IF NOT EXISTS idx_mart_genre_daily_metrics_date
    ON marts.mart_genre_daily_metrics (activity_date);

CREATE INDEX IF NOT EXISTS idx_mart_genre_daily_metrics_genre_date
    ON marts.mart_genre_daily_metrics (genre_id, activity_date);

CREATE TABLE IF NOT EXISTS marts.mart_activity_hourly (
    activity_date   DATE NOT NULL,
    hour_of_day     SMALLINT NOT NULL CHECK (hour_of_day BETWEEN 0 AND 23),
    day_of_week     SMALLINT NOT NULL,
    day_name        TEXT,
    is_weekend      BOOLEAN NOT NULL,
    game_sk         BIGINT NOT NULL,
    appid           BIGINT NOT NULL,
    game_name       TEXT,
    avg_players     NUMERIC(12, 2),
    max_players     BIGINT,
    samples         BIGINT NOT NULL DEFAULT 0,
    loaded_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (activity_date, hour_of_day, game_sk)
);

CREATE INDEX IF NOT EXISTS idx_mart_activity_hourly_date_hour
    ON marts.mart_activity_hourly (activity_date, hour_of_day);

CREATE INDEX IF NOT EXISTS idx_mart_activity_hourly_game
    ON marts.mart_activity_hourly (game_sk);

CREATE INDEX IF NOT EXISTS idx_mart_activity_hourly_game_date
    ON marts.mart_activity_hourly (game_sk, activity_date);

CREATE INDEX IF NOT EXISTS idx_mart_activity_hourly_day_hour
    ON marts.mart_activity_hourly (day_of_week, hour_of_day);

CREATE TABLE IF NOT EXISTS marts.dq_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_name   TEXT NOT NULL,
    run_id       TEXT,
    check_type   TEXT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('passed', 'warning', 'error')),
    severity     TEXT,
    metric_value NUMERIC,
    threshold    NUMERIC,
    details      JSONB,
    checked_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_marts_dq_results_check_checked_at
    ON marts.dq_results (check_name, checked_at DESC);

CREATE INDEX IF NOT EXISTS idx_marts_dq_results_run_id
    ON marts.dq_results (run_id);
